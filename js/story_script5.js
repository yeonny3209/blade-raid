// X-2 : 모은 조각에 담긴 이름을 하나씩 부른다
function nameRoll() {
  const keys = Object.keys(FRAGS).sort((a, b) => { const [, ma, na] = a.match(/f(\d)_(\d)/), [, mb, nb] = b.match(/f(\d)_(\d)/); return ma - mb || na - nb; });
  const lines = [];
  for (let i = 0; i < keys.length; i += 5) lines.push(['n', keys.slice(i, i + 5).map(k => FRAGS[k].title).join('. ') + '.']);
  cineInsert(lines);
}

